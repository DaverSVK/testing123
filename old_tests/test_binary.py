# ═══════════════════════════════════════════════════════════════════════════════

def test_elf_file_exists():
    """The compiled ELF must exist – proves the build succeeded."""
    assert ELF_FILE.exists(), (
        f"ELF not found: {ELF_FILE}. Build must succeed before binary tests run."
    )


def test_disassembly_file_exists():
    """disassembly.txt (from objdump) must be present."""
    assert DISASM_FILE.exists(), f"Missing: {DISASM_FILE}"


def test_symbols_file_exists():
    """symbols.txt (from nm) must be present."""
    assert SYMBOLS_FILE.exists(), f"Missing: {SYMBOLS_FILE}"


