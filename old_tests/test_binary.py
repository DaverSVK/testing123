# TEST GROUP 8 – MODER register configuration bits
# ═══════════════════════════════════════════════════════════════════════════════

def test_moder_pa4_output_bits_present():
    """
    PA4 in output mode requires MODER bits [9:8] = 01 → mask value 0x100.
    This value (or 0x10000 in 2-bit field position 8) must appear in the binary.
    """
    text = _disasm()
    # bits 9:8 set to 01 = 0x0100
    moder_pa4_out = 0x0100
    present = bool(re.search(
        rf"#\s*(?:0[xX])?{moder_pa4_out:x}\b",
        text, re.IGNORECASE
    ))
    # Some implementations may OR in larger values; just check the address appeared
    if not present:
        # Fall back: GPIOA_MODER_REG access implies MODER was configured
        present = _addr_in_main_disasm(GPIOA_BASE + 0x00)

    assert present, (
        f"MODER configuration for PA4 output (bits 9:8=01, mask 0x{moder_pa4_out:X}) "
        "not found. Configure PA4 as General Purpose Output in GPIOA MODER."
    )

# ═══════════════════════════════════════════════════════════════════════════════
# TEST GROUP 9 – edgeDetect in the binary (Assignment 2)
# ═══════════════════════════════════════════════════════════════════════════════

DEBOUNCE_SAMPLES = 100          # 100 samples * 1 ms = 100 ms debounce window


def _main_block() -> str:
    """Return the disassembly of main() only, or the whole listing as a fallback."""
    text = _disasm()
    m = re.search(r"<main>:.*?(?=\n\n|\Z)", text, re.DOTALL)
    return m.group(0) if m else text


def _calls_from_main(callee: str) -> bool:
    """True if main() contains a branch-with-link to the given function."""
    return bool(re.search(rf"\bbl(?:\.w)?\s+[0-9a-f]+\s*<{re.escape(callee)}>",
                          _main_block(), re.IGNORECASE))


def test_edge_detect_symbol_present():
    """
    'edgeDetect' must be present in the ELF – it is declared in assignment.h and
    defined in main.c.
    """
    syms = _symbols()
    assert re.search(r"\bedgeDetect\b", syms), (
        "Symbol 'edgeDetect' not found in the ELF. The function must be declared in "
        "Inc/assignment.h and defined in Src/main.c."
    )


def test_main_calls_edge_detect():
    """main() must actually call edgeDetect – the edge is evaluated in the app loop."""
    assert _calls_from_main("edgeDetect"), (
        "No 'bl <edgeDetect>' found in the disassembly of main(). The application loop "
        "has to call edgeDetect with the current state of the input pin."
    )


def test_main_calls_ll_mdelay():
    """
    main() must call LL_mDelay – the delay between two samples defines the length
    of the debounce window.
    """
    assert _calls_from_main("LL_mDelay"), (
        "No 'bl <LL_mDelay>' found in the disassembly of main(). The input pin has to "
        "be sampled with a defined period (SAMPLE_PERIOD_MS)."
    )


def test_debounce_samples_immediate_in_main():
    """
    The number of samples required for the 100 ms debounce (100 = 0x64) must be
    passed to edgeDetect – it appears as an immediate in main().
    objdump prints it either as '#100' or '#0x64'.
    """
    block = _main_block()
    present = bool(re.search(
        rf"#\s*{DEBOUNCE_SAMPLES}\b|#\s*0[xX]0*{DEBOUNCE_SAMPLES:x}\b",
        block, re.IGNORECASE
    ))
    assert present, (
        f"Immediate value {DEBOUNCE_SAMPLES} (0x{DEBOUNCE_SAMPLES:X}) not found in main(). "
        f"edgeDetect must be called with DEBOUNCE_SAMPLES = {DEBOUNCE_SAMPLES} so that "
        f"{DEBOUNCE_SAMPLES} samples * SAMPLE_PERIOD_MS = 100 ms debounce window."
    )


def test_edge_detect_uses_static_state():
    """
    edgeDetect keeps its state between calls, so its static variables end up in
    .bss/.data – the function must therefore reference a RAM address (0x20000000+).
    """
    text = _disasm()
    m = re.search(r"<edgeDetect>:.*?(?=\n\n|\Z)", text, re.DOTALL)
    assert m, (
        "Function 'edgeDetect' not found in the disassembly – it must be defined in "
        "Src/main.c."
    )
    body = m.group(0)

    assert re.search(r"\b20[0-9a-f]{6}\b", body, re.IGNORECASE), (
        "edgeDetect does not access any RAM variable (no 0x200xxxxx address in its "
        "disassembly). One call processes one sample, so the last stable pin state and "
        "the counter of identical samples must be kept in 'static' variables."
    )
