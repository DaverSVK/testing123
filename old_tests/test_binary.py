# TEST GROUP 3 – GPIOA base address appears in the binary
# ═══════════════════════════════════════════════════════════════════════════════

def test_gpioa_base_addr_in_disasm():
    """
    0x48000000 (GPIOA base) must appear in the disassembly.
    Any GPIO register access must load this base address.
    """
    assert _addr_in_disasm(GPIOA_BASE), (
        f"Address 0x{GPIOA_BASE:08X} (GPIOA base) not found in disassembly. "
        "This suggests GPIO macros may not be defined or GPIO access code is absent."
    )


def test_gpioa_register_in_main():
    """
    At least one GPIOA register address must appear in the main() function.
    Checks IDR (0x48000010), ODR (0x48000014), and BSRR (0x48000018).
    """
    idr_ok  = _addr_in_main_disasm(GPIOA_IDR)
    odr_ok  = _addr_in_main_disasm(GPIOA_ODR)
    bsrr_ok = _addr_in_main_disasm(GPIOA_BSRR)
    brr_ok  = _addr_in_main_disasm(GPIOA_BRR)

    assert idr_ok or odr_ok or bsrr_ok or brr_ok, (
        "No GPIOA register address (IDR/ODR/BSRR/BRR) found in main(). "
        "LED_ON, LED_OFF, and BUTTON_GET_STATE macros may be empty."
    )


# ═══════════════════════════════════════════════════════════════════════════════
# TEST GROUP 4 – RCC AHBENR clock enable
# ═══════════════════════════════════════════════════════════════════════════════

def test_rcc_ahbenr_addr_in_disasm():
    """
    0x40021014 (RCC AHBENR) must appear in the disassembly.
    Enabling the GPIOA peripheral clock requires a write to this register.
    """
    assert _addr_in_disasm(RCC_AHBENR), (
        f"Address 0x{RCC_AHBENR:08X} (RCC AHBENR) not found in disassembly. "
        "The GPIOA clock enable code is missing or the macro is wrong. "
        "Set bit 17 (IOPAEN) of RCC_AHBENR to enable the clock."
    )


def test_rcc_iopaen_bit_value_in_disasm():
    """
    The value used to set IOPAEN (bit 17 = 0x20000 = 131072) must appear in
    the binary – either as a Thumb-2 immediate (#0x20000) or as a 32-bit
    word in the literal pool (00020000).  Both forms are accepted.
    """
    iopaen_val = 1 << RCC_IOPAEN_BIT  # 0x20000 = 131072
    hex_str     = f"{iopaen_val:x}"    # "20000"
    text = _disasm()

    # Covers:
    #   #0x20000  – Thumb-2 ORR/AND immediate
    #   #20000    – same without 0x prefix
    #   #131072   – decimal immediate (some objdump versions)
    #   00020000  – 8-digit literal pool entry (no leading 0x)
    hex_present = bool(re.search(
        rf"#\s*(?:0[xX])?0*{hex_str}\b"    # immediate: #0x20000 / #20000
        rf"|#\s*{iopaen_val}\b"            # decimal:   #131072
        rf"|(?<![0-9a-fA-F])0{{0,7}}{hex_str}(?![0-9a-fA-F])",  # pool: 00020000
        text, re.IGNORECASE
    ))

    assert hex_present, (
        f"Value 0x{iopaen_val:05X} (IOPAEN = bit {RCC_IOPAEN_BIT} of AHBENR) "
        f"not found in disassembly (checked hex immediate, decimal immediate, "
        f"and 32-bit literal pool forms). "
        f"Make sure you enable bit 17 in RCC_AHBENR to clock GPIOA."
    )


# ═══════════════════════════════════════════════════════════════════════════════
# TEST GROUP 5 – PA4 LED bit in binary
# ═══════════════════════════════════════════════════════════════════════════════

LED_BIT    = 4
LED_MASK   = 1 << LED_BIT          # 0x10 – ODR/BRR form
BSRR_RESET = 1 << (LED_BIT + 16)  # 0x100000 – BSRR reset form

def test_led_bit4_value_in_disasm():
    """
    Bit-4 mask (0x10 for ODR/BRR or 0x100000 for BSRR reset) must appear
    in the disassembly to confirm PA4 is used for the LED.
    """
    text = _disasm()

    odr_mask  = bool(re.search(rf"\b{LED_MASK:x}\b|#\s*{LED_MASK}", text, re.IGNORECASE))
    bsrr_mask = bool(re.search(rf"\b{BSRR_RESET:x}\b|#\s*{BSRR_RESET}", text, re.IGNORECASE))

    assert odr_mask or bsrr_mask, (
        f"Bit-4 mask for PA4 LED not found in disassembly. "
        f"Expected 0x{LED_MASK:X} (ODR/BRR) or 0x{BSRR_RESET:X} (BSRR reset). "
        f"Check LED_ON and LED_OFF macro definitions."
    )


