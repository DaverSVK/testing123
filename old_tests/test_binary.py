"""
Binary analysis tests for Assignment 2 – VRS cvicenie 2 (edge detection + debounce)
Target MCU: STM32F303K8Tx (Cortex-M4)

These tests parse the disassembly / symbol files produced by the CI build job:
  disassembly.txt  – arm-none-eabi-objdump -d output
  symbols.txt      – arm-none-eabi-nm --numeric-sort output

The files are expected relative to the repository root (where the pipeline
drops them via 'arm-none-eabi-objdump -d build/… > disassembly.txt').

Register addresses verified (STM32F303K8, RM0316):
  GPIOA base  : 0x48000000
  GPIOA IDR   : 0x48000010
  GPIOA ODR   : 0x48000014
  GPIOA BSRR  : 0x48000018
  GPIOA BRR   : 0x48000028
  RCC  AHBENR : 0x40021014

Assignment 2 additions:
  edgeDetect must be present in the ELF and called from main()
  the debounce sample count (100) must be passed to it
"""

import re
from pathlib import Path

# ── Paths ─────────────────────────────────────────────────────────────────────
REPO_ROOT      = Path(__file__).resolve().parent.parent
DISASM_FILE    = REPO_ROOT / "disassembly.txt"
SYMBOLS_FILE   = REPO_ROOT / "symbols.txt"
ELF_FILE       = REPO_ROOT / "build" / "vrs_cv2_ll_programming.elf"

# ── Known register addresses ───────────────────────────────────────────────────
GPIOA_BASE   = 0x48000000
GPIOA_IDR    = 0x48000010
GPIOA_ODR    = 0x48000014
GPIOA_BSRR   = 0x48000018
GPIOA_BRR    = 0x48000028
RCC_AHBENR   = 0x40021014

# IOPAEN is bit 17 of RCC_AHBENR
RCC_IOPAEN_BIT = 17


# ── Helpers ───────────────────────────────────────────────────────────────────

def _disasm() -> str:
    assert DISASM_FILE.exists(), (
        f"disassembly.txt not found at {DISASM_FILE}. "
        "This file is generated by the build job – run the build first."
    )
    return DISASM_FILE.read_text(encoding="utf-8")


def _symbols() -> str:
    assert SYMBOLS_FILE.exists(), (
        f"symbols.txt not found at {SYMBOLS_FILE}. "
        "This file is generated by the build job."
    )
    return SYMBOLS_FILE.read_text(encoding="utf-8")


def _hex_pattern(addr: int) -> re.Pattern:
    """Regex that matches a hex address in objdump output (with or without leading zeros)."""
    # objdump typically shows addresses like  48000010  or  0x48000010
    hex_str = f"{addr:08x}"
    # Also match without leading zeros and mixed case
    return re.compile(
        rf"(?:0[xX])?{hex_str}\b|"         # 0x48000010 or 48000010
        rf"(?:0[xX])?{addr:x}\b",           # 0x48000010 short form
        re.IGNORECASE
    )


def _addr_in_disasm(addr: int) -> bool:
    """Return True if the given address appears anywhere in the disassembly."""
    text = _disasm()
    return bool(_hex_pattern(addr).search(text))


def _addr_in_main_disasm(addr: int) -> bool:
    """
    Return True if the address appears in the disassembly of the main() function.
    Isolates the main function's code block from the full disassembly.
    """
    text  = _disasm()
    # objdump labels functions like:  08000xxx <main>:
    m = re.search(r"<main>:.*?(?=\n\n|\Z)", text, re.DOTALL)
    if not m:
        # Fall back to whole disassembly
        return _addr_in_disasm(addr)
    return bool(_hex_pattern(addr).search(m.group(0)))


