"""
Binary analysis tests for Assignment 4 - VRS cvicenie 4 (USART2 + DMA)
Target MCU: STM32F303K8Tx (Cortex-M4)

These tests parse the artefacts produced by the CI build job:
  disassembly.txt  - arm-none-eabi-objdump -d output
  symbols.txt      - arm-none-eabi-nm --numeric-sort output
  vectors.txt      - arm-none-eabi-objdump -s -j .isr_vector output

The files are expected relative to the repository root.

Verified against the CMSIS device header (stm32f303x8.h):
  DMA1_Channel6_IRQn = 16  -> vector offset (16 + 16) * 4 = 0x080
  DMA1_Channel7_IRQn = 17  -> vector offset (16 + 17) * 4 = 0x084
  USART2_IRQn        = 38  -> vector offset (16 + 38) * 4 = 0x0D8

  USART2 base 0x40004400   ISR 0x…41C  ICR 0x…420  RDR 0x…424  TDR 0x…428
  DMA1   base 0x40020000
  DMA1 channel 6 base 0x4002006C -> CCR 0x4002006C, CNDTR 0x40020070
  DMA1 channel 7 base 0x40020080 -> CCR 0x40020080, CNDTR 0x40020084
"""

import re
from pathlib import Path

# -- Paths --------------------------------------------------------------------
REPO_ROOT    = Path(__file__).resolve().parent.parent
DISASM_FILE  = REPO_ROOT / "disassembly.txt"
SYMBOLS_FILE = REPO_ROOT / "symbols.txt"
VECTORS_FILE = REPO_ROOT / "vectors.txt"
ELF_FILE     = REPO_ROOT / "build" / "usart_DMA.elf"
SRC_DIR      = REPO_ROOT / "Src"
MAIN_C       = SRC_DIR / "main.c"

# -- Peripheral addresses -----------------------------------------------------
USART2_BASE   = 0x40004400
USART2_ISR    = 0x4000441C
USART2_RDR    = 0x40004424
USART2_TDR    = 0x40004428

DMA1_BASE     = 0x40020000
DMA1_CH6_CCR  = 0x4002006C
DMA1_CH6_NDTR = 0x40020070
DMA1_CH7_CCR  = 0x40020080
DMA1_CH7_NDTR = 0x40020084

# -- Vector table -------------------------------------------------------------
VECTOR_TABLE_ORIGIN = 0x08000000
IRQ_NUMBERS = {
    "DMA1_Channel6_IRQHandler": 16,
    "DMA1_Channel7_IRQHandler": 17,
    "USART2_IRQHandler": 38,
}


def _vector_offset(irq_number: int) -> int:
    return (16 + irq_number) * 4


# -- Helpers ------------------------------------------------------------------

def _disasm() -> str:
    assert DISASM_FILE.exists(), (
        f"disassembly.txt not found at {DISASM_FILE}. "
        "This file is generated by the build job - run the build first."
    )
    return DISASM_FILE.read_text(encoding="utf-8", errors="replace")


def _symbols() -> str:
    assert SYMBOLS_FILE.exists(), (
        f"symbols.txt not found at {SYMBOLS_FILE}. "
        "This file is generated by the build job."
    )
    return SYMBOLS_FILE.read_text(encoding="utf-8", errors="replace")


def _hex_pattern(addr: int) -> re.Pattern:
    """Regex matching a hex address in objdump output, with or without leading zeros."""
    hex_str = f"{addr:08x}"
    return re.compile(
        rf"(?:0[xX])?{hex_str}\b|"
        rf"(?:0[xX])?{addr:x}\b",
        re.IGNORECASE,
    )


def _addr_in_disasm(addr: int) -> bool:
    return bool(_hex_pattern(addr).search(_disasm()))


def _symbol_table() -> dict:
    """Parse symbols.txt into {name: (address, type)} from 'nm --numeric-sort'."""
    table = {}
    for line in _symbols().splitlines():
        m = re.match(r"^([0-9a-fA-F]+)\s+(\w)\s+(\S+)\s*$", line.strip())
        if m:
            table[m.group(3)] = (int(m.group(1), 16), m.group(2))
    return table


def _function_block(name: str):
    """Disassembly of a single function, or None when it is not in the listing."""
    m = re.search(rf"<{re.escape(name)}>:.*?(?=\n\n|\Z)", _disasm(), re.DOTALL)
    return m.group(0) if m else None


def _instruction_count(block: str) -> int:
    return len(re.findall(r"^\s*[0-9a-f]+:\s", block, re.MULTILINE))


def _calls(block: str, callee: str) -> bool:
    return bool(re.search(rf"\bbl(?:\.w)?\s+[0-9a-f]+\s*<{re.escape(callee)}>",
                          block, re.IGNORECASE))


def _student_functions() -> set:
    """Names of the functions defined in Src/*.c - the call graph walk stays inside them."""
    names = set()
    for path in SRC_DIR.glob("*.c"):
        text = path.read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.DOTALL)
        text = re.sub(r"//[^\n]*", " ", text)
        names.update(re.findall(
            r"^[ \t]*(?:[A-Za-z_]\w*[ \t\*]+)+([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{",
            text, re.MULTILINE))
    return names - {"if", "else", "while", "for", "switch", "return", "sizeof"}


def _reachable_block(name: str):
    """
    Disassembly of `name` followed by every function from Src/*.c that it calls,
    transitively. Splitting the work into helper functions is a legitimate design;
    library code (newlib, the inline LL helpers) is deliberately not followed.
    """
    first = _function_block(name)
    if first is None:
        return None
    own = _student_functions()
    seen, todo, blocks = {name}, [first], []
    while todo:
        block = todo.pop(0)
        blocks.append(block)
        for callee in re.findall(r"\bbl(?:\.w)?\s+[0-9a-f]+\s*<(\w+)>", block, re.IGNORECASE):
            if callee in own and callee not in seen:
                seen.add(callee)
                callee_block = _function_block(callee)
                if callee_block is not None:
                    todo.append(callee_block)
    return "\n\n".join(blocks)


def _addr_in(block: str, addr: int) -> bool:
    return bool(_hex_pattern(addr).search(block))


def _immediate_present(text: str, value: int) -> bool:
    """
    True when `value` shows up as an ARM immediate or as a literal-pool word,
    covering the renderings objdump uses:  #0x23  /  #35  /  00000023
    """
    hex_str = f"{value:x}"
    return bool(re.search(
        rf"#\s*(?:0[xX])?0*{hex_str}\b"
        rf"|#\s*{value}\b"
        rf"|(?<![0-9a-fA-F])0{{0,7}}{hex_str}(?![0-9a-fA-F])",
        text, re.IGNORECASE,
    ))


def _vector_word(offset: int):
    """
    Read one 32-bit little-endian word from the '.isr_vector' dump produced by
    'arm-none-eabi-objdump -s -j .isr_vector'. Returns None if vectors.txt is absent.
    """
    if not VECTORS_FILE.exists():
        return None

    address = VECTOR_TABLE_ORIGIN + offset
    row_addr = address & ~0xF
    column = (address & 0xF) // 4

    for line in VECTORS_FILE.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.match(r"^\s*([0-9a-f]+)\s+((?:[0-9a-f]{8}\s+){1,4})", line)
        if not m or int(m.group(1), 16) != row_addr:
            continue
        words = m.group(2).split()
        if column >= len(words):
            return None
        raw = words[column]
        # objdump prints the bytes in memory order - swap for little endian.
        return int.from_bytes(bytes.fromhex(raw), "little")
    return None


def _check_vector_installed(handler: str):
    """Shared body of the three vector-slot tests."""
    symbols = _symbol_table()
    assert handler in symbols, (
        f"'{handler}' is not in the symbol table - the interrupt handler is missing "
        f"from the firmware. It is provided in Src/stm32f3xx_it.c, do not delete it."
    )
    handler_addr, _ = symbols[handler]

    word = _vector_word(_vector_offset(IRQ_NUMBERS[handler]))
    if word is None:
        return  # vectors.txt is optional - covered by the symbol-type test

    expected = handler_addr | 1  # Thumb bit
    assert word == expected, (
        f"Vector table slot for {handler} (IRQn {IRQ_NUMBERS[handler]}, offset "
        f"0x{_vector_offset(IRQ_NUMBERS[handler]):03X}) contains 0x{word:08X}, "
        f"expected 0x{expected:08X}. The interrupt does not reach your handler."
    )


