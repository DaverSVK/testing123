def test_dma_and_usart_handlers_not_default():
    """
    The three handlers are provided in Src/stm32f3xx_it.c. If any of them is deleted,
    the weak alias from the startup file takes over and the interrupt is lost.
    """
    symbols = _symbol_table()
    assert "Default_Handler" in symbols, (
        "'Default_Handler' is not in the symbol table - symbols.txt looks wrong."
    )
    default_addr, _ = symbols["Default_Handler"]

    for handler in IRQ_NUMBERS:
        assert handler in symbols, (
            f"'{handler}' is missing from the firmware. It is part of the template "
            f"(Src/stm32f3xx_it.c) and drives the whole DMA reception - do not remove it."
        )
        addr, sym_type = symbols[handler]
        assert addr != default_addr, (
            f"'{handler}' still points at 'Default_Handler' (both at 0x{addr:08X}) - "
            f"the handler is not implemented."
        )
        assert sym_type.upper() == "T", (
            f"'{handler}' has symbol type '{sym_type}', expected 'T'. 'W' means the "
            f"weak alias from the startup file is still being used."
        )


def test_dma1_channel6_vector_installed():
    """DMA1_Channel6_IRQn = 16 -> vector table offset 0x080."""
    _check_vector_installed("DMA1_Channel6_IRQHandler")


def test_dma1_channel7_vector_installed():
    """DMA1_Channel7_IRQn = 17 -> vector table offset 0x084."""
    _check_vector_installed("DMA1_Channel7_IRQHandler")


def test_usart2_vector_installed():
    """USART2_IRQn = 38 -> vector table offset 0x0D8."""
    _check_vector_installed("USART2_IRQHandler")


def test_usart2_configured_in_init():
    """MX_USART2_UART_Init has to touch the USART2 peripheral."""
    block = _function_block("MX_USART2_UART_Init")
    assert block is not None, (
        "No <MX_USART2_UART_Init>: block in the disassembly - the initialisation "
        "function is missing from the firmware."
    )
    assert _addr_in(block, USART2_BASE) or _addr_in_disasm(USART2_BASE), (
        f"The USART2 base address 0x{USART2_BASE:08X} does not appear anywhere in the "
        f"firmware. USART2 is never configured."
    )


def test_dma1_configured_in_init():
    """The DMA1 controller has to be configured for the USART transfers."""
    assert _addr_in_disasm(DMA1_BASE) or _addr_in_disasm(DMA1_CH6_CCR), (
        f"Neither the DMA1 base address 0x{DMA1_BASE:08X} nor the channel 6 control "
        f"register 0x{DMA1_CH6_CCR:08X} appears in the firmware - the DMA is never "
        f"configured, so USART2 reception cannot work."
    )


def test_main_does_not_read_rdr():
    """
    Reception goes USART -> DMA -> interrupt -> callback. Reading the receive data
    register inside main() is the polling solution this assignment replaces.
    """
    block = _function_block("main")
    if block is None:
        return
    assert not _addr_in(block, USART2_RDR), (
        f"The address 0x{USART2_RDR:08X} (USART2 RDR - the receive data register) "
        f"appears inside main(). The received characters must be collected by the DMA "
        f"and delivered through the HT/TC/IDLE interrupts, not polled in the main loop."
    )


def test_printf_float_is_linked():
    """
    The buffer load is printed with '%f'. newlib-nano leaves the floating point
    formatter out unless the link line asks for it. Only relevant when main.c really
    uses a float conversion - printing the load as "%u.%u" needs no formatter.
    """
    if MAIN_C.exists():
        source = MAIN_C.read_text(encoding="utf-8", errors="replace").replace("%%", "")
        literals = " ".join(re.findall(r'"((?:\\.|[^"\\])*)"', source))
        if not re.search(r"%[-+ #0-9.]*[fgeFGE]", literals):
            return
    symbols = _symbol_table()
    has_float = any("printf_float" in name for name in symbols)
    assert has_float, (
        "The floating point formatter is not linked into the firmware, so the '%f' "
        "conversion in the buffer-state message prints nothing. Add '-u _printf_float' "
        "to the linker flags (it is already in Makefile.ci) or format the load value "
        "without a float conversion."
    )


