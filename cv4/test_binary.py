def test_process_dma_data_present():
    """
    proccesDmaData is only kept by the linker when it is actually referenced,
    i.e. when it has been registered as the callback.
    """
    symbols = _symbol_table()
    assert "proccesDmaData" in symbols or _function_block("proccesDmaData"), (
        "'proccesDmaData' is not in the firmware. Either it is not defined, or it is "
        "never referenced and the linker dropped it - register it from main() with "
        "USART2_RegisterCallback(proccesDmaData)."
    )


def test_process_dma_data_is_not_empty():
    """An unimplemented stub compiles to little more than a return."""
    block = _reachable_block("proccesDmaData")
    if block is None:
        return
    count = _instruction_count(block)
    assert count >= 15, (
        f"'proccesDmaData' compiles to only {count} instructions, which is an empty or "
        f"near-empty function. It has to detect the '#' and '$' delimiters, count the "
        f"small and capital letters and enforce the 35 character limit."
    )


def test_frame_delimiters_in_binary():
    """'#' (0x23) opens a frame and '$' (0x24) closes it."""
    block = _reachable_block("proccesDmaData")
    if block is None:
        return
    missing = []
    if not _immediate_present(block, 0x23):
        missing.append("'#' (0x23)")
    if not _immediate_present(block, 0x24):
        missing.append("'$' (0x24)")
    assert not missing, (
        f"'proccesDmaData' never compares the received character against "
        f"{' or '.join(missing)}. A set of characters starts with '#' and ends with "
        f"'$' - both have to be tested for."
    )


def test_letter_range_bounds_in_binary():
    """
    Distinguishing case needs the 'a'/'z' or 'A'/'Z' bounds - or islower()/isupper(),
    which newlib expands inline into a lookup in its '_ctype_' table.
    """
    block = _reachable_block("proccesDmaData")
    if block is None:
        return
    lower = _immediate_present(block, 0x61) or _immediate_present(block, 0x7A)
    upper = _immediate_present(block, 0x41) or _immediate_present(block, 0x5A)

    symbols = _symbol_table()
    ctype = any(_calls(block, fn) for fn in ("islower", "isupper", "__locale_ctype_ptr"))
    if "_ctype_" in symbols:
        ctype = ctype or _addr_in(block, symbols["_ctype_"][0])

    assert (lower and upper) or ctype, (
        "'proccesDmaData' does not compare the character against both the small "
        "('a' = 0x61 .. 'z' = 0x7A) and the capital ('A' = 0x41 .. 'Z' = 0x5A) letter "
        "range, and does not use islower()/isupper() either, so it cannot be counting "
        "the two kinds separately."
    )


def test_callback_registered_in_main():
    """The callback has to be handed to the USART driver."""
    block = _reachable_block("main")
    if block is None:
        return
    assert _calls(block, "USART2_RegisterCallback"), (
        "main() never calls USART2_RegisterCallback(). Without it "
        "USART2_CheckDmaReception has no callback to deliver the received bytes to and "
        "proccesDmaData never runs."
    )


