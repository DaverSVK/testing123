def test_check_dma_reception_present():
    """The function must be in the binary."""
    assert _function_block("USART2_CheckDmaReception") is not None, (
        "No <USART2_CheckDmaReception>: block in the disassembly. The function is "
        "called from all three interrupt handlers - it must exist."
    )


def test_check_dma_reception_is_not_empty():
    """An unimplemented stub compiles to little more than a return."""
    block = _reachable_block("USART2_CheckDmaReception")
    if block is None:
        return
    count = _instruction_count(block)
    assert count >= 12, (
        f"'USART2_CheckDmaReception' compiles to only {count} instructions, which is an "
        f"empty or near-empty function. It has to read the DMA transfer counter, work "
        f"out how many new bytes arrived, forward each of them to the callback and "
        f"re-arm the channel."
    )


def test_check_dma_reception_reads_transfer_counter():
    """The number of received bytes comes from CNDTR of channel 6."""
    block = _reachable_block("USART2_CheckDmaReception")
    if block is None:
        return
    reads_counter = (_addr_in(block, DMA1_CH6_NDTR)
                     or _addr_in(block, DMA1_CH6_CCR)
                     or _addr_in(block, DMA1_BASE)
                     or _calls(block, "LL_DMA_GetDataLength"))
    assert reads_counter, (
        f"'USART2_CheckDmaReception' never touches the DMA channel 6 registers "
        f"(CNDTR is at 0x{DMA1_CH6_NDTR:08X}). Without reading the remaining transfer "
        f"length there is no way to know how many bytes the DMA has written."
    )


def test_check_dma_reception_uses_the_rx_buffer():
    """The received bytes are read out of bufferUSART2dma."""
    symbols = _symbol_table()
    block = _reachable_block("USART2_CheckDmaReception")
    if block is None or "bufferUSART2dma" not in symbols:
        return
    buf_addr, _ = symbols["bufferUSART2dma"]
    assert _addr_in(block, buf_addr), (
        f"'USART2_CheckDmaReception' never references 'bufferUSART2dma' "
        f"(0x{buf_addr:08X}). That array is where the DMA puts the received data - "
        f"the function has to read the new bytes out of it."
    )


def test_check_dma_reception_does_not_delay():
    """It runs in interrupt context and must not block."""
    block = _reachable_block("USART2_CheckDmaReception")
    if block is None:
        return
    for delay in ("LL_mDelay", "HAL_Delay", "LL_Init1msTick"):
        assert not _calls(block, delay), (
            f"'USART2_CheckDmaReception' calls {delay}(). The function runs inside the "
            f"DMA and USART interrupt handlers - a blocking delay there stalls the "
            f"reception and loses incoming characters."
        )


